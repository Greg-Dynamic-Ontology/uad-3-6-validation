"""IT-54R4S1: behavior classification is a bounded construction worker."""

from __future__ import annotations

from uuid import uuid4

import pytest
from rdflib import Graph, Literal, Namespace, RDF, URIRef
from rdflib.collection import Collection
from rdflib.namespace import PROV, SH

from app.services.constraint_behavior_classification import (
    classify_governed_constraint_behavior,
)
from app.services.construction_exchange import (
    UADEX,
    ConstructionStageResultRecord,
    read_construction_stage_result,
)


CV = Namespace("https://dynamicontology.com/uad36/constraint-vocabulary#")


def _round_trip(graph: Graph) -> Graph:
    return Graph().parse(data=graph.serialize(format="turtle"), format="turtle")


@pytest.mark.parametrize(
    "matching_behaviors,expected_status",
    [(1, "GREEN"), (0, "EXCEPTION"), (2, "EXCEPTION")],
    ids=["classified", "unknown", "ambiguous"],
)
def test_it_54_r4_s1_returns_only_contracted_output_or_exception(
    matching_behaviors: int,
    expected_status: str,
) -> None:
    ns = Namespace(f"urn:uad36:test:it54r4s1:{uuid4().hex}:")
    constraint = ns.constraint
    requirement = Literal("Supply the governed value in the applicable context.")
    violation = Literal("The governed value is absent in the applicable context.")
    schema_path = [ns.parent_resource, ns.data_resource]

    upstream = Graph()
    for triple in (
        (constraint, RDF.type, CV.NormalizedConstraint),
        (constraint, CV.requirementText, requirement),
        (constraint, CV.violationCondition, violation),
        (constraint, CV.boundLogicalSchemaResource, ns.data_resource),
        (constraint, CV.applicableContext, ns.context),
        (constraint, PROV.wasDerivedFrom, ns.source),
        (ns.context, RDF.type, CV.ConstraintContext),
        (ns.context, CV.schemaPath, ns.path),
    ):
        upstream.add(triple)
    Collection(upstream, ns.path, schema_path)
    upstream = _round_trip(upstream)

    registry = Graph()
    behaviors = {ns[f"behavior-{index}"] for index in range(matching_behaviors)}
    for behavior in behaviors:
        registry.add((behavior, RDF.type, CV.ValidationBehavior))
        registry.add((behavior, CV.requirementText, requirement))
        registry.add((behavior, CV.violationCondition, violation))
    registry = _round_trip(registry)
    upstream_before = set(upstream)
    registry_before = set(registry)
    output = Graph()

    result = classify_governed_constraint_behavior(
        context_graph=upstream,
        established_behaviors_graph=registry,
        constraint_id=str(constraint),
        output_graph=output,
    )
    assert isinstance(result, ConstructionStageResultRecord)
    assert set(upstream) == upstream_before
    assert set(registry) == registry_before
    assert upstream_before.issubset(set(output))

    downstream = _round_trip(output)
    recorded = read_construction_stage_result(
        exchange_graph=downstream, result_id=str(result.result_id)
    )
    assert recorded == result
    assert recorded.constraint_id == str(constraint)
    assert recorded.construction_stage == "validation-behavior"
    assert recorded.construction_status == expected_status

    for predicate, expected in (
        (CV.requirementText, requirement),
        (CV.violationCondition, violation),
        (CV.boundLogicalSchemaResource, ns.data_resource),
        (CV.applicableContext, ns.context),
    ):
        assert set(downstream.objects(constraint, predicate)) == {expected}
    assert set(downstream.predicate_objects(ns.context)) == set(
        upstream.predicate_objects(ns.context)
    )
    assert list(Collection(downstream, ns.path)) == schema_path

    classifications = set(downstream.objects(constraint, CV.behaviorClassification))
    knowledge = set(downstream.objects(result.result_id, UADEX.stageKnowledge))
    if expected_status == "GREEN":
        assert len(classifications) == 1
        classification = next(iter(classifications))
        assert isinstance(classification, URIRef)
        assert knowledge == {classification}
        assert set(downstream.objects(classification, CV.validationBehavior)) == behaviors
        assert recorded.available_for_downstream is True
        assert recorded.requires_review is False
        assert recorded.exception_reason is None
    else:
        assert not classifications
        assert not knowledge
        assert recorded.available_for_downstream is False
        assert recorded.requires_review is True
        assert recorded.exception_reason

    # Check only newly produced knowledge. Preserved upstream knowledge is
    # not generated by this worker and must not be misidentified as its output.
    added = set(output) - upstream_before - registry_before
    allowed_constraint_predicates = {
        CV.behaviorClassification,
        CV.validationBehavior,
        CV.requirementText,
        CV.violationCondition,
        CV.applicableContext,
        CV.candidateBehavior,
        CV.newBehaviorClassificationRequired,
    }
    for _, predicate, object_value in added:
        assert not str(predicate).startswith(str(SH)), "The worker generated SHACL."
        if isinstance(object_value, URIRef):
            assert not str(object_value).startswith(str(SH)), (
                "The worker generated a SHACL shape or runtime validation finding."
            )
        if str(predicate).startswith(str(CV)):
            assert predicate in allowed_constraint_predicates, (
                f"The worker generated knowledge outside behavior classification: {predicate}"
            )
        if predicate == RDF.type:
            assert object_value in {
                CV.ValidationBehaviorClassification,
                UADEX.ConstructionStageResult,
            }, "The worker generated another stage's artifact or report finding."

    assert set(downstream.subjects(RDF.type, CV.ValidationBehavior)) == behaviors
    assert set(downstream.subjects(RDF.type, CV.NormalizedConstraint)) == {constraint}
    assert set(downstream.subjects(RDF.type, CV.ConstraintContext)) == {ns.context}
